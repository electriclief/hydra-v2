#!/usr/bin/env node
/**
 * Export the services this node can make into a library another node can start from.
 *
 * The `.js` service file stays the single source of truth: it is loaded here through the SAME sandbox the
 * catalog uses (data only, no execution), validated, and then written out as JSON. Nothing is retyped, so the
 * export cannot drift from what this node actually serves.
 *
 *   node scripts/export-library.mjs            # write library/<name>/service.json for every valid service
 *   node scripts/export-library.mjs --check    # exit 1 if a library file is stale or missing (for a gate)
 *
 * What goes in the library is the DEFINITION, not the machine: no paths, no ports, no promises about what this
 * box has. A node that pulls a definition checks its own disk against it and says what it can and cannot hold.
 */
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '..');
const SERVICES = path.join(ROOT, 'module', 'Services');
const LIBRARY = path.join(ROOT, 'library');
const CHECK = process.argv.includes('--check');

const loaderUrl = pathToFileURL(path.join(SERVICES, 'public', 'js', 'serviceFile.js')).href;
const { loadServiceFile } = await import(loaderUrl);

const files = fs
  .readdirSync(path.join(SERVICES, 'services'))
  .filter((name) => name.endsWith('.js'))
  .sort();

let written = 0;
let stale = 0;
let refused = 0;

for (const file of files) {
  const result = loadServiceFile(path.join(SERVICES, 'services', file));
  if (!result.definition) {
    refused += 1;
    console.log(`  refused  ${file}: ${result.error || 'schema errors'}`);
    continue;
  }

  const def = result.definition;
  const dir = path.join(LIBRARY, def.name);
  const target = path.join(dir, 'service.json');
  // the hash is over the DEFINITION only (never the export metadata), so a re-export of unchanged data is stable
  const digest = crypto.createHash('sha256').update(JSON.stringify(def)).digest('hex');
  const payload = {
    ...def,
    library: {
      sha256: digest,
      from: file,
      note: 'Generated by scripts/export-library.mjs from the sandboxed service file. Do not hand-edit: edit the .js and re-export.',
    },
  };
  const body = JSON.stringify(payload, null, 2) + '\n';

  if (CHECK) {
    const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : null;
    const same = current && JSON.stringify(JSON.parse(current), null, 2) + '\n' === body;
    if (!same) {
      stale += 1;
      console.log(`  STALE    ${def.name}: library/${def.name}/service.json is missing or out of date`);
    }
    continue;
  }

  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(target, body, 'utf8');
  written += 1;
  console.log(`  wrote    library/${def.name}/service.json  (${(body.length / 1024).toFixed(1)} KiB)`);
}

if (CHECK) {
  console.log(`\nLibrary — ${stale ? `${stale} stale` : 'up to date'} — ${stale ? 'RED' : 'GREEN'}`);
  process.exit(stale ? 1 : 0);
}
console.log(`\nLibrary — ${written} exported, ${refused} refused`);
